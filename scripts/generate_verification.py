def latest_per_tool(results: list) -> list:
    """Keep only the most recent successful run for each tool."""
    best: dict[str, object] = {}
    for result in sorted(results, key=lambda r: (r.started_at or "", r.finished_at or "")):
        best[result.tool] = result
    return list(best.values())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output", default=str(paths.project_root() / "docs" / "final-verification.md")
    )
    args = parser.parse_args(argv)

    config = LabConfig.load()
    assessment = collect(config, verify_findings=False)
    integrity = evidence_module.verify(config.tool_names())
    runs = latest_per_tool(assessment.results)

    counts = assessment.all_findings
    correlation = assessment.correlation

    lines: list[str] = []
    add = lines.append

    add("# Final verification")
    add("")
    add(
        "Generated by `scripts/generate_verification.py` from recorded run data, "
        "so this document reflects what the lab actually did rather than what it "
        "was intended to do."
    )
    add("")
    add(f"- Generated: {assessment.generated_at}")
    add(f"- Machine: {platform.system()} {platform.release()}, Python {platform.python_version()}")
    add(f"- Authorized target: {config.authorized_url}")
    add(f"- Configuration: {config.source or 'built-in defaults'}")
    add("")

    add("## Tool-by-tool verification")
    add("")
    add("| Component | Status | Transport / version | Exit | Findings | Raw artifact |")
    add("| --- | --- | --- | --- | --- | --- |")
    for result in runs:
        artifact = result.raw_artifacts[0] if result.raw_artifacts else "-"
        add(
            f"| {result.tool} | **{result.status.value}** | "
            f"{result.tool_version[:46]} | {result.exit_code} | "
            f"{result.finding_count} | `{artifact}` |"
        )
    add("")

    add("## What each tool actually did")
    add("")
    for result in runs:
        add(f"### {result.tool} — {TOOL_PURPOSE.get(result.tool, '')}")
        add("")
        add(f"- Status: **{result.status.label}**")
        add(f"- Duration: {result.duration_seconds:.1f}s")
        if result.command:
            add(f"- Command: `{' '.join(result.command)}`")
        if result.errors:
            add(f"- Errors: {'; '.join(result.errors[:3])}")
        if result.warnings:
            add(f"- Warnings: {'; '.join(result.warnings[:3])}")
        if result.notes:
            add(f"- Notes: {'; '.join(result.notes[:4])}")
        add(
            f"- Findings: {result.finding_count} "
            f"({', '.join(f'{k}={v}' for k, v in result.severity_counts().items() if v)})"
        )
        for finding in result.findings[:5]:
            add(f"  - `{finding.severity.value}` {finding.title[:96]}")
        if result.finding_count > 5:
            add(f"  - ... and {result.finding_count - 5} more")
        add("")

    add("## Normalization")
    add("")
    add(f"- Findings normalized: **{len(counts)}**")
    add("- Schema fields: tool, category, severity, title, description, target, endpoint, "
        "evidence, recommendation, timestamp, verification_status")
    add("- Severity vocabulary: CRITICAL, HIGH, MEDIUM, LOW, INFO")
    if counts:
        tallies: dict[str, int] = {}
        for finding in counts:
            tallies[finding.severity.value] = tallies.get(finding.severity.value, 0) + 1
        add("- Distribution: " + ", ".join(f"{k}={v}" for k, v in sorted(tallies.items())))
    add("")

    add("## Correlation")
    add("")
    summary = correlation.summary()
    add(f"- Correlation groups: **{summary['total_groups']}**")
    add(f"- Confirmed by two or more tools: **{summary['confirmed_by_multiple_tools']}**")
    add(f"- Single-tool observations: **{summary['single_tool_observations']}**")
    add(f"- Contributing tools: {', '.join(summary['contributing_tools']) or '-'}")
    add("")
    if correlation.confirmed:
        add("### Corroborated findings")
        add("")
        add("| Finding | Severity | Tools | Endpoints |")
        add("| --- | --- | --- | --- |")
        for group in correlation.confirmed:
            endpoints = ", ".join(group.endpoints[:3]) or "-"
            add(
                f"| {group.title[:70]} | {group.severity.value} | "
                f"{', '.join(group.tools)} | {endpoints} |"
            )
        add("")
    else:
        add("No issue was reported by more than one tool in this run.")
        add("")

    add("## Evidence")
    add("")
    add(f"- Evidence records: **{len(assessment.evidence_records)}**")
    add(
        f"- Integrity: **{integrity.intact}/{integrity.checked}** artifacts match "
        "their recorded sha256"
    )
    if integrity.modified:
        add(f"- Modified artifacts: {', '.join(integrity.modified)}")
    if integrity.missing:
        add(f"- Missing artifacts: {', '.join(integrity.missing)}")
    add("")

    add("## Reports")
    add("")
    finals = sorted(paths.final_dir().glob("assessment-*")) if paths.final_dir().is_dir() else []
    if finals:
        add(f"- Report files in `reports/final/`: **{len(finals)}**")
        for item in finals[-6:]:
            add(f"  - `{paths.relative_to_root(item)}` ({item.stat().st_size} bytes)")
    else:
        add("- No consolidated report has been generated yet. "
            "Run `python -m bcssl report`.")
    add("")

    add("## Safety controls")
    add("")
    add("| Control | Implementation | Detail |")
    add("| --- | --- | --- |")
    for name, where, detail in SAFETY_CONTROLS:
        add(f"| {name} | `{where}` | {detail} |")
    add("")

    add("## Protected projects")
    add("")
    add("| Project | Expectation | How it was integrated |")
    add("| --- | --- | --- |")
    add("| `Web-Security-Scanner` (Project #08) | unmodified | imported read-only / invoked as a subprocess |")
    add("| `BCSSL-Student-Web-Security-Lab` | untouched | never read into this project |")
    add("")

    destination = Path(args.output)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {destination} ({destination.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
